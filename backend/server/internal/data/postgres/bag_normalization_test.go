// 保留正式事务能力，记录快判是否仍进入了写事务。
type normalizationObservedDB struct {
	*sql.DB
	begins int
}

// 测试参照事务直接使用底层连接，只统计仓储自身发起的事务。
func (db *normalizationObservedDB) BeginTx(ctx context.Context, opts *sql.TxOptions) (*sql.Tx, error) {
	db.begins++
	return db.DB.BeginTx(ctx, opts)
}

// 独立本地 schema 中与原整理器逐行比较，覆盖顺序、溢出、零堆叠及绑定/有效期/实例分组。
func TestContainerNormalizationFastCheckPostgres(t *testing.T) {
	db := openLocalRuntimeFixture(t, bagPageFixtureSQL+`
ALTER TABLE item_definition ADD COLUMN max_stack integer DEFAULT 1;
ALTER TABLE player_container_item ADD COLUMN updated_at timestamptz DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE player_container_item ALTER COLUMN id SET NOT NULL;
ALTER TABLE player_container_item ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 1000);
CREATE TABLE normalization_initial AS SELECT * FROM player_container_item WITH NO DATA;
`)
	ctx := context.Background()
	for _, test := range []struct {
		name       string
		quantities []int
		dirty      bool
		split      string
	}{
		{"empty", nil, false, ""}, {"one_partial", []int{2}, false, ""},
		{"full_then_partial", []int{3, 2}, false, ""}, {"partial_then_full", []int{2, 3}, true, ""},
		{"split_partials", []int{1, 1}, true, ""}, {"over_capacity_stack", []int{8}, true, ""},
		{"zero_then_full", []int{0, 3}, true, ""}, {"full_then_zero", []int{3, 0}, true, ""},
		{"all_zero", []int{0, 0}, false, ""}, {"bound_groups", []int{1, 1}, false, "bound"},
		{"expiry_groups", []int{1, 1}, false, "expiry"}, {"instance_rows", []int{8, 8}, false, "uid"},
		{"unstackable", []int{8}, false, "unstackable"},
	} {
		t.Run(test.name, func(t *testing.T) {
			exec := func(query string, args ...any) {
				t.Helper()
				if _, err := db.ExecContext(ctx, query, args...); err != nil {
					t.Fatal(err)
				}
			}
			exec("DELETE FROM player_container_item")
			stack := 3
			if test.split == "unstackable" {
				stack = 1
			}
			exec("UPDATE item_definition SET max_stack=$1 WHERE item_id=1", stack)
			for index, quantity := range test.quantities {
				uid := ""
				if test.split == "uid" {
					uid = fmt.Sprintf("instance_%d", index)
				}
				expiry := any(nil)
				if test.split == "expiry" {
					expiry = fmt.Sprintf("2030-01-%02d", index+1)
				}
				exec(`INSERT INTO player_container_item(id,player_id,container_type,slot_index,item_id,item_uid,quantity,is_bound,expire_at) VALUES($1,1,'bag',$2,1,$3,$4,$5,$6)`, index+1, index*2+1, uid, quantity, test.split == "bound" && index == 1, expiry)
			}
			exec("TRUNCATE normalization_initial")
			exec("INSERT INTO normalization_initial SELECT * FROM player_container_item")
			var dirty bool
			if err := db.QueryRowContext(ctx, runtimeContainerNeedsNormalizationQuery, 1, "bag").Scan(&dirty); err != nil {
				t.Fatal(err)
			}
			if dirty != test.dirty {
				t.Fatalf("dirty=%t want %t", dirty, test.dirty)
			}
			observed := &normalizationObservedDB{DB: db}
			if err := NewBagRepository(observed).normalizeRuntimeContainer(ctx, 1, bag.ContainerTypeBag); err != nil {
				t.Fatal(err)
			}
			expectedBegins := 0
			if test.dirty {
				expectedBegins = 1
			}
			if observed.begins != expectedBegins {
				t.Fatalf("transactions=%d want %d", observed.begins, expectedBegins)
			}
			fast := readNormalizationRows(t, db)
			exec("DELETE FROM player_container_item")
			exec("INSERT INTO player_container_item SELECT * FROM normalization_initial")
			tx, err := db.BeginTx(ctx, nil)
			if err != nil {
				t.Fatal(err)
			}
			defer rollbackTx(tx)
			if err := normalizeRuntimeContainers(ctx, tx, 1, bag.ContainerTypeBag); err != nil {
				t.Fatal(err)
			}
			if err := tx.Commit(); err != nil {
				t.Fatal(err)
			}
			legacy := readNormalizationRows(t, db)
			if !reflect.DeepEqual(fast, legacy) {
				t.Fatalf("different normalized results: fast=%v old=%v", fast, legacy)
			}
			if err := db.QueryRowContext(ctx, runtimeContainerNeedsNormalizationQuery, 1, "bag").Scan(&dirty); err != nil || dirty {
				t.Fatalf("still dirty=%t err=%v", dirty, err)
			}
		})
	}
}

// 比较业务行，忽略新拆堆的记录 ID 与更新时间差异。
func readNormalizationRows(t *testing.T, db *sql.DB) []string {
	t.Helper()
	rows, err := db.Query(`SELECT concat_ws('|',slot_index,item_id,COALESCE(item_uid,''),quantity,is_bound,COALESCE(expire_at::text,'')) FROM player_container_item WHERE player_id=1 AND container_type='bag' ORDER BY slot_index`)
	if err != nil {
		t.Fatal(err)
	}
	defer rows.Close()
	var result []string
	for rows.Next() {
		var row string
		if err := rows.Scan(&row); err != nil {
			t.Fatal(err)
		}
		result = append(result, row)
	}
	if err := rows.Err(); err != nil {
		t.Fatal(err)
	}
	return result
}
