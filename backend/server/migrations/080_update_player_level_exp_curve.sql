-- 按策划表更新玩家 1~100 级升级所需经验（player_level_config.exp_required）。
-- level 表示「处于该等级时升到下一级」所需经验；100 级为 0，不再升级。
-- 若尚未执行 035/043，本脚本会先补齐表结构与默认字段，再写入经验曲线。

CREATE TABLE IF NOT EXISTS player_level_config (
  level INTEGER PRIMARY KEY,
  exp_required BIGINT NOT NULL DEFAULT 0,
  attr_points INTEGER NOT NULL DEFAULT 0,
  status SMALLINT NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_player_level_config_level CHECK (level >= 1 AND level <= 100),
  CONSTRAINT ck_player_level_config_exp_required CHECK (exp_required >= 0),
  CONSTRAINT ck_player_level_config_attr_points CHECK (attr_points >= 0)
);

ALTER TABLE player_level_config
  ADD COLUMN IF NOT EXISTS bonus_atk INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS bonus_hp_max INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS bonus_spd INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS bonus_mana INTEGER NOT NULL DEFAULT 0;

DROP TRIGGER IF EXISTS trg_player_level_config_updated_at ON player_level_config;
